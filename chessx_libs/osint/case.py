"""Cases: named, persisted collections of findings with JSON / CSV / Markdown export."""
import csv, io, json, os, re, time
from typing import List
from .types import Finding
from .cache import default_dir

SAFE = re.compile(r"^[A-Za-z0-9_.-]{1,64}$")


class Case:
    def __init__(self, name: str, findings: List[Finding] = None, notes: str = "", created=None, entities=None):
        if not SAFE.match(name):
            raise ValueError("case name must match %s" % SAFE.pattern)
        self.name, self.notes = name, notes
        self.findings = list(findings or [])
        self.entities = list(entities or [])
        self.created = created or time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())

    def add(self, entity, findings):
        if str(entity) not in self.entities:
            self.entities.append(str(entity))
        self.findings.extend(findings)

    def to_dict(self):
        return {"name": self.name, "created": self.created, "notes": self.notes, "entities": self.entities,
                "findings": [f.to_dict() for f in self.findings]}

    @classmethod
    def from_dict(cls, d):
        return cls(d["name"], [Finding.from_dict(x) for x in d.get("findings", [])], d.get("notes", ""),
                   d.get("created"), d.get("entities"))

    # ---- export
    def to_json(self):
        return json.dumps(self.to_dict(), indent=2, ensure_ascii=False)

    def to_csv(self):
        buf = io.StringIO()
        w = csv.writer(buf)
        w.writerow(["entity", "source", "sources", "kind", "title", "url", "confidence", "fetched_at", "data"])
        for f in self.findings:
            w.writerow([str(f.entity), f.source, "|".join(f.sources), f.kind, f.title, f.url,
                        "%.2f" % f.confidence, f.fetched_at, json.dumps(f.data, ensure_ascii=False, sort_keys=True)])
        return buf.getvalue()

    def to_markdown(self):
        out = ["# Case %s" % self.name, "", "Created: %s  " % self.created,
               "Entities: %s" % (", ".join("`%s`" % e for e in self.entities) or "-"), ""]
        if self.notes:
            out += [self.notes, ""]
        by = {}
        for f in self.findings:
            by.setdefault(str(f.entity), []).append(f)
        for ent, fs in by.items():
            out += ["## %s" % ent, "", "| conf | kind | finding | sources |", "|---|---|---|---|"]
            for f in sorted(fs, key=lambda f: -f.confidence):
                t = f.title.replace("|", "\\|")
                out.append("| %.2f | %s | %s | %s |" % (f.confidence, f.kind, "[%s](%s)" % (t, f.url) if f.url else t,
                                                       ", ".join(f.sources)))
            out.append("")
        out.append("_Public sources only; verify before acting. Generated by ChessX OSINT._")
        return "\n".join(out) + "\n"

    def export(self, fmt):
        return {"json": self.to_json, "csv": self.to_csv, "md": self.to_markdown}[fmt]()


class CaseStore:
    def __init__(self, root=None):
        self.root = root or os.path.join(default_dir(), "cases")

    def path(self, name):
        if not SAFE.match(name):
            raise ValueError("bad case name")
        return os.path.join(self.root, name + ".json")

    def save(self, case):
        os.makedirs(self.root, exist_ok=True)
        tmp = self.path(case.name) + ".tmp"
        with open(tmp, "w", encoding="utf-8") as f:
            f.write(case.to_json())
        os.replace(tmp, self.path(case.name))

    def load(self, name):
        with open(self.path(name), encoding="utf-8") as f:
            return Case.from_dict(json.load(f))

    def open(self, name):
        return self.load(name) if os.path.exists(self.path(name)) else Case(name)

    def list(self):
        if not os.path.isdir(self.root):
            return []
        return sorted(f[:-5] for f in os.listdir(self.root) if f.endswith(".json"))

    def delete(self, name):
        p = self.path(name)
        if os.path.exists(p):
            os.remove(p)
            return True
        return False
